export function buildFaqKeyboard(
  node: FaqNode,
  opts: { ai?: InlineKeyboardButton | null } = {},
): InlineKeyboard {
  const rows: InlineKeyboard = [];

  if (node.children) {
    for (const child of node.children) {
      rows.push([{ text: child.title, callback_data: `faq:${child.id}` }]);
    }
  }

  if (node.id !== 'menu') {
    const parent = findParent(node.id);
    const parentId = parent?.id ?? 'menu';
    rows.push([
      { text: '⬅️ Назад', callback_data: `faq:${parentId}` },
      { text: '🏠 В меню', callback_data: 'faq:menu' },
    ]);
  }

  // Порядок строк здесь и есть смысл: быстрый ответ стоит НАД оператором,
  // потому что отвечает за секунды и в большинстве случаев закрывает вопрос.
  // Живой человек остаётся ниже и никуда не девается — иначе кнопка помощника
  // читалась бы как «оператора больше нет».
  if (opts.ai) {
    rows.push([opts.ai]);
  }
  rows.push([{ text: '🆘 Связаться со специалистом', callback_data: 'contact' }]);
  return rows;
}

